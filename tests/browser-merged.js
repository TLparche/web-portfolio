// Shared representatives, category details, five interests and accessible fallbacks.
async page => {
  const base=process.env.PREVIEW_URL || 'http://127.0.0.1:3111/web-portfolio/';
  const check=(ok,message)=>{if(!ok)throw new Error(message);};
  const anchors=[['experience','projects'],['activities','projects'],['publications','projects'],['certifications','education'],['awards','education'],['skills','education']];
  for(const [hash,owner] of anchors) {
    await page.goto(base+'#'+hash);
    const selected=page.locator(owner==='projects'?'#work-domain-ai':'#'+owner+'-category-'+hash);
    await page.waitForFunction(({owner,hash})=>owner==='projects'?document.querySelector('[data-widget=works]')?.getAttribute('data-view')==='domains':document.getElementById(owner+'-category-'+hash)?.getAttribute('aria-selected')==='true',{owner,hash});
    await page.reload();
    await selected.waitFor();
    await page.waitForFunction(({owner,hash})=>owner==='projects'?document.querySelector('[data-widget=works]')?.getAttribute('data-view')==='domains':document.getElementById(owner+'-category-'+hash)?.getAttribute('aria-selected')==='true',{owner,hash});
  }
  await page.goto(base+'#projects');
  const work=page.locator('[data-widget=works]');
  await work.locator('#work-domain-platform').waitFor();
  check(await work.locator('[data-work-domain]').count()===6,'Six domains required');
  check(await work.locator('[id^=projects-category-]').count()===0,'Only domain navigation remains');
  check(await work.locator('#projects-title').textContent()==='경험','Experience title');
  await work.locator('#work-domain-platform').press('Enter');
  check(await work.getAttribute('data-view')==='gallery','Field opens a gallery');
  check(await work.locator('[data-work-detail]').getAttribute('data-item-id')==='showcase-project-01','First field record is selected');
  await work.getByRole('button',{name:'콘텐츠 제작',exact:true}).click();
  check(await work.locator('[id^=work-open-]').count()===3,'Creation filter');
  check(await work.locator('#work-open-holo-studio').getAttribute('aria-selected')==='true','Filter selects its first record');
  await work.locator('#work-open-yt-edit').click();
  check(await work.locator('[data-work-detail]').getAttribute('data-item-id')==='yt-edit','Filmstrip changes the displayed record');
  await work.locator('#work-open-yt-edit').press('Home');
  check(await work.locator('#work-open-holo-studio').getAttribute('aria-selected')==='true','Home selects first record');
  await work.locator('#work-open-holo-studio').press('End');
  check(await work.locator('#work-open-yt-edit').getAttribute('aria-selected')==='true','End selects last record');
  await page.keyboard.press('Escape');
  check(await work.locator('#work-domain-platform').evaluate(n=>n===document.activeElement),'Field focus restored');
  await work.locator('#work-domain-platform').press('Enter');
  await work.getByRole('combobox',{name:'분야 변경'}).selectOption('misc');
  check(await work.locator('#work-open-showcase-activity-01').count()===1,'Activities included by domain');
  check(await work.locator('#work-open-blog-visualization').count()===1,'Projects alongside activities');
  await page.goto(base+'works/?domain=platform&category=creation');
  await page.waitForFunction(()=>document.querySelector('[role=status]')?.textContent.includes('3개의 기록'));
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('[role=status]')?.textContent.includes('3개의 기록'));
  await page.getByRole('link',{name:'AI',exact:true}).click();
  await page.goBack();
  check(page.url().includes('category=creation'),'URL restored');
  await page.getByRole('link',{name:/holo-studio.*기록 읽기/}).click();
  await page.getByRole('heading',{level:1,name:'holo-studio · 점군 장면 편집기'}).waitFor();
  await page.getByRole('button',{name:'점군 장면과 슬롯 타임라인을 편집하는 holo-studio 확대'}).click();
  check(await page.locator('dialog[open]').count()===1,'Image enlargement');
  await page.keyboard.press('Escape');
  check(await page.locator('dialog[open]').count()===0,'Escape closes image');
  check(await page.locator('video').getAttribute('preload')==='none','Video deferred');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No horizontal overflow');
  await page.goto(base+'#interests');
  const tabs=page.locator('[data-widget=interests] [role=tab]');
  check(await tabs.count()===5,'Existing interest topics preserved');
  const first=await page.locator('[data-widget=interests] [role=tab][aria-selected=true]').getAttribute('id');
  await page.getByRole('button',{name:'다음 관심분야',exact:true}).click();
  await page.waitForFunction(first=>document.querySelector('[data-widget=interests] [role=tab][aria-selected=true]')?.id!==first,first);
  return {oldAnchors:6,domains:6,creationProjects:3,fieldGallery:true,filmstripKeyboard:true,focusRestored:true,urlFilters:true,imageDialog:true,videoDeferred:true,interestTopics:5};
}
